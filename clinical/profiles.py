"""Patient discharge profiles and profile-driven personalization (PS-03 §3.3, §3.4).

A discharge profile carries the conditions and medications generated by
Synthea, plus the clinical flags the scoring engine needs. Every rule records
the *specific profile fact* that caused it, because PS-03 requires each alert
to explain the reading, the rule and the profile information behind it.

Three personalization rules are implemented:

1. SpO2 Scale 2 (target 88-92%) for documented hypercapnic respiratory failure.
2. Per-patient rolling baselines, to catch gradual drift (see ``baseline.py``).
3. Beta-blocker pulse correction: beta-blockade blunts the chronotropic
   response, so a normal pulse must not be read as reassurance.

Rule 3 is a documented heuristic for this decision-support prototype, not a
validated clinical adjustment. It is deliberately explicit and auditable.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

SNOMED = "http://snomed.info/sct"
RXNORM = "http://www.nlm.nih.gov/research/umls/rxnorm"

# Beta-blockers blunt the heart-rate response to deterioration.
BETA_BLOCKER_GENERICS: frozenset[str] = frozenset(
    {
        "metoprolol",
        "bisoprolol",
        "atenolol",
        "carvedilol",
        "propranolol",
        "nebivolol",
        "labetalol",
        "sotalol",
    }
)

HYPERCAPNIC_MARKERS: tuple[str, ...] = (
    "hypercapnic",
    "hypercapnia",
    "type 2 respiratory failure",
    "type ii respiratory failure",
    "chronic respiratory failure",
)

COPD_MARKERS: tuple[str, ...] = (
    "chronic obstructive",
    "copd",
    "emphysema",
    "chronic bronchitis",
)

DEFAULT_PULSE_CORRECTION_BPM = 10.0


@dataclass(frozen=True)
class Condition:
    code: str
    display: str
    system: str = SNOMED

    def to_dict(self) -> dict[str, str]:
        return {"code": self.code, "display": self.display, "system": self.system}


@dataclass(frozen=True)
class Medication:
    code: str
    display: str
    generic: str
    system: str = RXNORM

    def to_dict(self) -> dict[str, str]:
        return {
            "code": self.code,
            "display": self.display,
            "generic": self.generic,
            "system": self.system,
        }


@dataclass(frozen=True)
class PersonalizationRule:
    """One profile-driven adjustment, with the fact that justifies it."""

    rule_id: str
    title: str
    profile_fact: str
    effect: str

    def to_dict(self) -> dict[str, str]:
        return {
            "rule_id": self.rule_id,
            "title": self.title,
            "profile_fact": self.profile_fact,
            "effect": self.effect,
        }


@dataclass
class DischargeProfile:
    patient_id: str
    display_name: str
    age_years: int
    sex: str
    discharged_on: str
    conditions: tuple[Condition, ...] = ()
    medications: tuple[Medication, ...] = ()
    hypercapnic_respiratory_failure: bool = False
    spo2_target: tuple[float, float] = (94.0, 98.0)
    pulse_correction_bpm: float = 0.0
    notes: str = ""
    source: str = "synthea"
    scenario: str = ""

    # ------------------------------------------------------------- derived
    @property
    def spo2_scale(self) -> int:
        return 2 if self.hypercapnic_respiratory_failure else 1

    @property
    def beta_blocked(self) -> bool:
        return self.pulse_correction_bpm > 0

    def rules(self) -> list[PersonalizationRule]:
        out: list[PersonalizationRule] = []
        if self.hypercapnic_respiratory_failure:
            fact = self._hypercapnic_fact()
            out.append(
                PersonalizationRule(
                    rule_id="spo2_scale_2",
                    title="SpO₂ Scale 2 (target 88–92%)",
                    profile_fact=fact,
                    effect=(
                        "SpO₂ scored on NEWS2 Scale 2 instead of Scale 1; "
                        "88–92% is the target range and scores 0."
                    ),
                )
            )
        if self.beta_blocked:
            fact = self._beta_blocker_fact()
            out.append(
                PersonalizationRule(
                    rule_id="beta_blocker_pulse",
                    title="Beta-blocker pulse correction",
                    profile_fact=fact,
                    effect=(
                        f"Pulse scored with a +{self.pulse_correction_bpm:g} bpm correction "
                        "because beta-blockade blunts the heart-rate response; "
                        "a normal pulse is not treated as reassurance."
                    ),
                )
            )
        out.append(
            PersonalizationRule(
                rule_id="rolling_baseline",
                title="Per-patient rolling baseline",
                profile_fact=f"Baseline learned from this patient's own readings ({self.patient_id}).",
                effect=(
                    "Vitals are compared with the patient's own recent typical values, "
                    "so gradual drift away from their normal is detected even when "
                    "every reading is still inside population reference ranges."
                ),
            )
        )
        return out

    def _hypercapnic_fact(self) -> str:
        for condition in self.conditions:
            text = condition.display.lower()
            if any(marker in text for marker in HYPERCAPNIC_MARKERS + COPD_MARKERS):
                return f"Condition: {condition.display} (SNOMED {condition.code})"
        return "Documented hypercapnic respiratory failure"

    def _beta_blocker_fact(self) -> str:
        for medication in self.medications:
            if medication.generic.lower() in BETA_BLOCKER_GENERICS:
                return f"Medication: {medication.display} (RxNorm {medication.code})"
        return "Beta-blocker therapy"

    # ------------------------------------------------------- serialization
    def to_dict(self) -> dict[str, Any]:
        return {
            "patient_id": self.patient_id,
            "display_name": self.display_name,
            "age_years": self.age_years,
            "sex": self.sex,
            "discharged_on": self.discharged_on,
            "conditions": [c.to_dict() for c in self.conditions],
            "medications": [m.to_dict() for m in self.medications],
            "hypercapnic_respiratory_failure": self.hypercapnic_respiratory_failure,
            "spo2_scale": self.spo2_scale,
            "spo2_target": list(self.spo2_target),
            "beta_blocked": self.beta_blocked,
            "pulse_correction_bpm": self.pulse_correction_bpm,
            "notes": self.notes,
            "source": self.source,
            "scenario": self.scenario,
            "rules": [r.to_dict() for r in self.rules()],
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "DischargeProfile":
        return cls(
            patient_id=data["patient_id"],
            display_name=data["display_name"],
            age_years=int(data["age_years"]),
            sex=data["sex"],
            discharged_on=data["discharged_on"],
            conditions=tuple(
                Condition(c["code"], c["display"], c.get("system", SNOMED))
                for c in data.get("conditions", [])
            ),
            medications=tuple(
                Medication(m["code"], m["display"], m.get("generic", m["display"]), m.get("system", RXNORM))
                for m in data.get("medications", [])
            ),
            hypercapnic_respiratory_failure=bool(data.get("hypercapnic_respiratory_failure", False)),
            spo2_target=tuple(data.get("spo2_target", (94.0, 98.0))),
            pulse_correction_bpm=float(data.get("pulse_correction_bpm", 0.0)),
            notes=data.get("notes", ""),
            source=data.get("source", "synthea"),
            scenario=data.get("scenario", ""),
        )


def derive_flags(
    conditions: tuple[Condition, ...],
    medications: tuple[Medication, ...],
    home_oxygen: bool = False,
) -> dict[str, Any]:
    """Infer scoring flags from a Synthea patient's conditions and medications.

    Hypercapnia is inferred from an explicit respiratory-failure diagnosis, or
    from COPD plus documented long-term oxygen support. ``home_oxygen`` is set
    from an oxygen-concentrator Device in the record: acute inpatient oxygen
    is not evidence of chronic hypercapnic failure, so it does not count.
    The inference is recorded so a clinician can see why Scale 2 was chosen.
    """
    texts = [c.display.lower() for c in conditions]
    hypercapnic = any(any(marker in t for marker in HYPERCAPNIC_MARKERS) for t in texts)
    has_copd = any(any(marker in t for marker in COPD_MARKERS) for t in texts)
    if not hypercapnic and has_copd:
        hypercapnic = home_oxygen or any(
            "oxygen" in t or "respiratory failure" in t for t in texts
        )

    beta_blocker = next(
        (m for m in medications if m.generic.lower() in BETA_BLOCKER_GENERICS), None
    )
    return {
        "hypercapnic_respiratory_failure": hypercapnic,
        "spo2_target": (88.0, 92.0) if hypercapnic else (94.0, 98.0),
        "pulse_correction_bpm": DEFAULT_PULSE_CORRECTION_BPM if beta_blocker else 0.0,
        "beta_blocker_medication": beta_blocker.display if beta_blocker else None,
    }